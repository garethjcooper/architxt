/**
 * C4 Model Structurizr DSL export.
 *
 * Produces a valid Structurizr DSL file (.dsl) from the contextual graph using
 * the C4 element mappings stored on entity types and the C4 relationship
 * descriptions stored on edge types.
 *
 * Nodes are emitted as the DSL element that matches their mapped C4 element:
 *   Person          -> person
 *   SoftwareSystem  -> softwareSystem
 *   Container       -> container
 *   Component       -> component
 *
 * Because Container and Component elements must be nested inside a parent
 * softwareSystem/container in the Structurizr DSL, any standalone mapped
 * Container/Component is placed inside a synthetic root softwareSystem named
 * after the bank. Components are further nested inside a synthetic container
 * named "Components" within that root system. Person and SoftwareSystem
 * elements are emitted at the top level of the model.
 *
 * Unmapped nodes default to softwareSystem.
 *
 * Edges are emitted as DSL relationships (`source -> target "description"`).
 * A single systemLandscape view is generated including all top-level elements
 * and all relationships.
 *
 * @see https://docs.structurizr.com/dsl/language
 */

const C4_ELEMENT_DSL = {
  Person: 'person',
  SoftwareSystem: 'softwareSystem',
  Container: 'container',
  Component: 'component',
};

/**
 * Create a valid Structurizr DSL identifier from an arbitrary node id.
 *
 * DSL identifiers may contain letters, digits and underscores, must start
 * with a letter, and are case-insensitive. We normalise to lower case and
 * collapse non-alphanumerics to underscores. Leading digits are prefixed with
 * "id_" to keep the identifier valid.
 */
function makeDslId(id) {
  if (!id) return 'unknown';
  let sanitized = String(id)
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!sanitized) return 'unknown';
  if (/^[0-9]/.test(sanitized)) {
    sanitized = `id_${sanitized}`;
  }
  return sanitized;
}

function escapeDslString(value) {
  if (value === null || value === undefined) return '';
  return String(value).replace(/"/g, '\\"');
}

function nodeLabel(node) {
  return (
    node.properties?.name ||
    node.properties?.display_name ||
    node.properties?.label ||
    node.labels?.find((l) => l !== 'canonical' && l !== 'candidate') ||
    node.labels?.[0] ||
    node.id
  );
}

function edgeDescription(edge, mapping) {
  const raw =
    mapping?.c4Description ||
    edge.type ||
    edge.properties?.label ||
    'relates to';
  return escapeDslString(raw);
}

/**
 * Format an element assignment at the current indentation level.
 * Structurizr DSL element syntax: `id = keyword "label" "description" "technology"`
 */
function formatElement(indent, id, keyword, label, description = '', technology = '') {
  const escapedLabel = escapeDslString(label);
  const escapedDescription = escapeDslString(description);
  const escapedTechnology = escapeDslString(technology);

  const parts = [`${indent}${id} = ${keyword}`, `"${escapedLabel}"`];
  if (escapedDescription) {
    parts.push(`"${escapedDescription}"`);
  }
  if (escapedTechnology && escapedDescription) {
    parts.push(`"${escapedTechnology}"`);
  } else if (escapedTechnology) {
    // Structurizr requires an empty description string before technology.
    parts.push('""', `"${escapedTechnology}"`);
  }
  return parts.join(' ');
}

function formatRelationship(indent, sourceRef, targetRef, description) {
  return `${indent}${sourceRef} -> ${targetRef} "${description}"`;
}

/**
 * Build a Structurizr DSL representation of the graph.
 *
 * @param {Array<{id: string, labels: string[], properties: Record<string, any>}>} nodes
 * @param {Array<{id: string, source_id: string, target_id: string, type: string | null, properties: Record<string, any>}>} edges
 * @param {Object} meta
 * @param {boolean} undirected
 * @param {Map<string, {c4Element: string | null, archimateElement: string | null, typeName: string | null, defaulted: boolean}>} nodeMap
 * @param {Map<string, {c4Description: string | null, archimateRelationship: string | null, typeName: string | null, defaulted: boolean}>} edgeMap
 * @returns {string}
 */
export function toC4StructurizrDsl(nodes, edges, meta, undirected, nodeMap, edgeMap) {
  const bankName = meta.bank_id || 'export';
  const rootSystemId = makeDslId(`${bankName}_system`);
  const componentsContainerId = makeDslId(`${bankName}_components`);

  // node.id -> { dslId, keyword, ref (full DSL reference) }
  const emittedNodes = new Map();
  const topLevelRefs = [];

  const lines = [];
  lines.push('workspace {');
  lines.push('  !identifiers hierarchical');
  lines.push('');
  lines.push(`  name "${escapeDslString(bankName)}"`);
  lines.push(`  description "Generated by architxt at ${escapeDslString(meta.generated_at || new Date().toISOString())}"`);
  lines.push('');
  lines.push('  model {');

  // Pass 1: emit top-level Person and SoftwareSystem elements.
  for (const node of nodes) {
    const mapping = nodeMap.get(node.id) || {};
    const c4Element = mapping.c4Element || null;
    const keyword = C4_ELEMENT_DSL[c4Element] || 'softwareSystem';
    const dslId = makeDslId(node.id);

    emittedNodes.set(node.id, { dslId, keyword, ref: dslId });

    if (keyword === 'person' || keyword === 'softwareSystem') {
      topLevelRefs.push(dslId);
      const label = nodeLabel(node);
      const description = node.properties?.description || mapping.typeName || '';
      lines.push(formatElement('    ', dslId, keyword, label, description));
    }
  }

  // Pass 2: emit synthetic root softwareSystem containing Container and Component
  // children. Component nodes are nested inside a synthetic "Components"
  // container so the DSL remains valid even for a flat source graph.
  const childNodes = nodes.filter((n) => {
    const mapping = nodeMap.get(n.id) || {};
    const keyword = C4_ELEMENT_DSL[mapping.c4Element] || 'softwareSystem';
    return keyword === 'container' || keyword === 'component';
  });

  if (childNodes.length > 0) {
    topLevelRefs.push(rootSystemId);
    lines.push(
      formatElement(
        '    ',
        rootSystemId,
        'softwareSystem',
        bankName,
        'Synthetic grouping system for exported containers and components'
      ) + ' {'
    );

    const containerNodes = childNodes.filter((n) => {
      const mapping = nodeMap.get(n.id) || {};
      return C4_ELEMENT_DSL[mapping.c4Element] === 'container';
    });

    const componentNodes = childNodes.filter((n) => {
      const mapping = nodeMap.get(n.id) || {};
      return C4_ELEMENT_DSL[mapping.c4Element] === 'component';
    });

    for (const node of containerNodes) {
      const mapping = nodeMap.get(node.id) || {};
      const dslId = makeDslId(node.id);
      const label = nodeLabel(node);
      const description = node.properties?.description || mapping.typeName || '';
      emittedNodes.get(node.id).ref = `${rootSystemId}.${dslId}`;
      lines.push(formatElement('      ', dslId, 'container', label, description));
    }

    if (componentNodes.length > 0) {
      lines.push(
        formatElement(
          '      ',
          componentsContainerId,
          'container',
          'Components',
          'Synthetic container for exported components'
        ) + ' {'
      );
      for (const node of componentNodes) {
        const mapping = nodeMap.get(node.id) || {};
        const dslId = makeDslId(node.id);
        const label = nodeLabel(node);
        const description = node.properties?.description || mapping.typeName || '';
        emittedNodes.get(node.id).ref = `${rootSystemId}.${componentsContainerId}.${dslId}`;
        lines.push(formatElement('        ', dslId, 'component', label, description));
      }
      lines.push('      }');
    }

    lines.push('    }');
  }

  // Emit relationships using hierarchical references so nested containers and
  // components can be connected to top-level elements. Duplicate relationships
  // between the same ordered pair are merged into a single relationship with
  // combined descriptions, because the Structurizr DSL parser rejects parallel
  // edges between the same elements.
  const relationshipMap = new Map();
  for (const edge of edges) {
    const source = emittedNodes.get(edge.source_id);
    const target = emittedNodes.get(edge.target_id);
    if (!source || !target) continue;

    const mapping = edgeMap.get(edge.id) || {};
    const description = edgeDescription(edge, mapping);
    const isUndirected = undirected || edge.properties?.directed === false;
    const key = isUndirected
      ? [source.ref, target.ref].sort().join('\u0000')
      : `${source.ref}\u0000${target.ref}`;

    const existing = relationshipMap.get(key);
    if (existing) {
      if (!existing.descriptions.includes(description)) {
        existing.descriptions.push(description);
      }
    } else {
      relationshipMap.set(key, {
        sourceRef: source.ref,
        targetRef: target.ref,
        descriptions: [description],
        undirected: isUndirected,
      });
    }
  }

  const relationshipLines = [];
  for (const rel of relationshipMap.values()) {
    const combinedDescription = rel.descriptions.join(' / ');
    // Structurizr DSL only supports the -> operator. For undirected edges we
    // emit both directions to preserve the bidirectional semantic.
    if (rel.undirected) {
      relationshipLines.push(formatRelationship('    ', rel.sourceRef, rel.targetRef, combinedDescription));
      relationshipLines.push(formatRelationship('    ', rel.targetRef, rel.sourceRef, combinedDescription));
    } else {
      relationshipLines.push(formatRelationship('    ', rel.sourceRef, rel.targetRef, combinedDescription));
    }
  }

  if (relationshipLines.length > 0) {
    lines.push('');
    lines.push(...relationshipLines);
  }

  lines.push('  }');

  // Emit a systemLandscape view for all top-level elements, plus a container
  // view scoped to the synthetic root system so that nested containers and
  // components are rendered in a drilled-in diagram.
  lines.push('');
  lines.push('  views {');
  if (topLevelRefs.length > 0) {
    lines.push('    systemLandscape {');
    lines.push('      include *');
    lines.push('      autoLayout');
    lines.push('    }');
  }
  if (childNodes.length > 0) {
    lines.push(`    container ${rootSystemId} {`);
    lines.push('      include *');
    lines.push('      autoLayout');
    lines.push('    }');
  }
  lines.push('  }');
  lines.push('}');

  return lines.join('\n');
}

export default toC4StructurizrDsl;
