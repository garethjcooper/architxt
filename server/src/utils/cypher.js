/**
 * Cypher export utilities.
 *
 * Produces a self-contained Neo4j-flavoured Cypher script using inline literals.
 * The output can be piped directly into cypher-shell or executed from a .cypher
 * file in Neo4j Browser / Desktop.
 */

function escapeString(value) {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'");
}

function cypherLiteral(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) return 'null';
    return String(value);
  }
  if (typeof value === 'string') {
    return `'${escapeString(value)}'`;
  }
  return `'${escapeString(JSON.stringify(value))}'`;
}

function toIdentifier(value) {
  if (value === null || value === undefined) return '';
  let s = String(value).replace(/[^A-Za-z0-9_]/g, '_');
  if (/^[0-9_]/.test(s)) {
    s = `id_${s}`;
  }
  if (!s) s = 'id';
  return s;
}

function escapeBacktick(value) {
  return String(value).replace(/`/g, '``');
}

function formatLabels(labels) {
  const parts = (labels || [])
    .filter(Boolean)
    .map((label) => `:\`${escapeBacktick(label)}\``);
  if (parts.length === 0) return '';
  return parts.join('');
}

function formatRelType(type) {
  if (!type) return 'RELATED_TO';
  let t = String(type).replace(/[^A-Za-z0-9_]/g, '_').toUpperCase();
  if (/^[0-9_]/.test(t)) t = `REL_${t}`;
  if (!t) t = 'RELATED_TO';
  return `\`${escapeBacktick(t)}\``;
}

function escapePropertyKey(key) {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) return key;
  return `\`${escapeBacktick(key)}\``;
}

function formatPropertyMap(properties, extra = {}) {
  const entries = [];
  const seen = new Set();

  function add(key, value) {
    if (seen.has(key)) return;
    seen.add(key);
    entries.push(`${escapePropertyKey(key)}: ${cypherLiteral(value)}`);
  }

  for (const [key, value] of Object.entries(properties || {})) {
    if (key === 'label') continue;
    add(key, value);
  }
  for (const [key, value] of Object.entries(extra)) {
    add(key, value);
  }

  if (entries.length === 0) return '';
  return ` { ${entries.join(', ')} }`;
}

function formatHeaderValue(value) {
  if (value === null || value === undefined) return '';
  return String(value);
}

export function toCypher(nodes, edges, meta, undirected = false) {
  const lines = [];

  const generatedAt = meta?.generated_at
    ? String(meta.generated_at).replace(/\*/g, ' ')
    : new Date().toISOString();
  lines.push('// Cypher export generated by architxt');
  lines.push(`// server_id: ${formatHeaderValue(meta?.server_id)}`);
  lines.push(`// bank_id: ${formatHeaderValue(meta?.bank_id)}`);
  lines.push(`// generated_at: ${generatedAt}`);
  lines.push('// format: cypher');
  lines.push(`// node_count: ${nodes.length}`);
  lines.push(`// edge_count: ${edges.length}`);
  lines.push('');

  const nodeIdToVar = new Map();
  const usedVars = new Set();
  const seenNodeIds = new Set();

  function allocateVar(id) {
    if (nodeIdToVar.has(id)) return nodeIdToVar.get(id);
    let base = toIdentifier(id);
    if (!base) base = 'n';
    let v = base;
    let counter = 1;
    while (usedVars.has(v)) {
      v = `${base}_${counter}`;
      counter += 1;
    }
    usedVars.add(v);
    nodeIdToVar.set(id, v);
    return v;
  }

  for (const node of nodes) {
    if (!node.id || seenNodeIds.has(node.id)) continue;
    seenNodeIds.add(node.id);

    const v = allocateVar(node.id);
    const labels = formatLabels(node.labels);
    const displayLabel = node.properties?.name
      || node.properties?.label
      || (node.labels || [])[0]
      || node.id;
    const props = formatPropertyMap(node.properties, {
      id: node.id,
      label: displayLabel,
    });

    lines.push(`CREATE (${v}${labels}${props});`);
  }

  if (nodes.length > 0 && edges.length > 0) {
    lines.push('');
  }

  const usedEdgeIds = new Set();
  for (const edge of edges) {
    const sourceVar = nodeIdToVar.get(edge.source_id) ?? toIdentifier(edge.source_id);
    const targetVar = nodeIdToVar.get(edge.target_id) ?? toIdentifier(edge.target_id);

    const edgeDirected = edge.properties?.directed;
    const edgeUndirected = typeof edgeDirected === 'boolean'
      ? !edgeDirected
      : undirected;

    const relType = formatRelType(edge.type);
    const displayLabel = edge.type
      || edge.properties?.label
      || `${edge.source_id} -> ${edge.target_id}`;
    const props = formatPropertyMap(edge.properties, {
      id: edge.id,
      source_id: edge.source_id,
      target_id: edge.target_id,
      type: edge.type,
      label: displayLabel,
    });

    let edgeId = edge.id ? toIdentifier(edge.id) : 'e';
    let counter = 1;
    const baseEdgeId = edgeId;
    while (usedEdgeIds.has(edgeId)) {
      edgeId = `${baseEdgeId}_${counter}`;
      counter += 1;
    }
    usedEdgeIds.add(edgeId);

    lines.push(`// edge: ${edge.id || edgeId}`);
    lines.push(`MATCH (${sourceVar} { id: ${cypherLiteral(edge.source_id)} }), (${targetVar} { id: ${cypherLiteral(edge.target_id)} })`);
    lines.push(`CREATE (${sourceVar})-[${edgeId}:${relType}${props}]-${edgeUndirected ? `(${targetVar});` : `>(${targetVar});`}`);
  }

  return lines.join('\n');
}

export default toCypher;
