import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { toCypher } from '../src/utils/cypher.js';

describe('cypher serializer', () => {
  it('produces a well-formed Cypher script with header comment', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: ['Entity'], properties: { name: 'Alpha' } }],
      [],
      { server_id: 1, bank_id: 'Mozart-API' },
      false,
    );
    assert.ok(cypher.startsWith('// Cypher export generated by architxt'));
    assert.ok(cypher.includes('// format: cypher'));
    assert.ok(cypher.includes('CREATE (A:`Entity` {'));
    assert.ok(cypher.includes(`id: 'A'`));
    assert.ok(cypher.includes(`label: 'Alpha'`));
  });

  it('sanitizes node ids and label names for Cypher identifiers', () => {
    const cypher = toCypher(
      [{ id: '123-svc:SVC-005', labels: ['Service', 'Component'], properties: { name: 'svc 5' } }],
      [],
      {},
      false,
    );
    assert.ok(cypher.includes('CREATE (id_123_svc_SVC_005:`Service`:`Component` {'));
    assert.ok(cypher.includes(`id: '123-svc:SVC-005'`));
    assert.ok(cypher.includes(`name: 'svc 5'`));
  });

  it('escapes single quotes and backslashes in string literals', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: { name: "it's \\ a test" } }],
      [],
      {},
      false,
    );
    assert.ok(cypher.includes("name: 'it\\'s \\\\ a test'"));
  });

  it('creates directed edges with relationship type and properties', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: {} }, { id: 'B', labels: [], properties: {} }],
      [{ id: 'e1', source_id: 'A', target_id: 'B', type: 'sends', properties: { weight: 3 } }],
      {},
      false,
    );
    assert.ok(cypher.includes('MATCH (A { id: \'A\' }), (B { id: \'B\' })'));
    assert.ok(cypher.includes('CREATE (A)-[e1:`SENDS` {'));
    assert.ok(cypher.includes('weight: 3'));
    assert.ok(cypher.includes(`type: 'sends'`));
    assert.ok(cypher.includes(']->(B);'));
  });

  it('honours the global undirected flag', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: {} }, { id: 'B', labels: [], properties: {} }],
      [{ id: 'e1', source_id: 'A', target_id: 'B', type: 'links', properties: {} }],
      {},
      true,
    );
    assert.ok(cypher.includes('CREATE (A)-[e1:`LINKS` {') || cypher.includes('CREATE (A)-[e1:`LINKS`]'));
    assert.ok(cypher.includes(']-(B);'));
    assert.ok(!cypher.includes(']->(B);'));
  });

  it('lets per-edge directed=false override the global directed default', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: {} }, { id: 'B', labels: [], properties: {} }],
      [{
        id: 'e1',
        source_id: 'A',
        target_id: 'B',
        type: 'knows',
        properties: { directed: false },
      }],
      {},
      false,
    );
    assert.ok(cypher.includes(']-(B);'));
    assert.ok(!cypher.includes(']->(B);'));
  });

  it('JSON-stringifies object and array properties', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: { obj: { a: 1 }, arr: [1, 2] } }],
      [],
      {},
      false,
    );
    assert.ok(cypher.includes(`obj: '{"a":1}'`));
    assert.ok(cypher.includes(`arr: '[1,2]'`));
  });

  it('declares boolean and numeric properties as native Cypher literals', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: { count: 42, ok: true, score: 1.5 } }],
      [],
      {},
      false,
    );
    assert.ok(cypher.includes('count: 42'));
    assert.ok(cypher.includes('ok: true'));
    assert.ok(cypher.includes('score: 1.5'));
  });

  it('does not emit empty property maps', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: {} }],
      [],
      {},
      false,
    );
    assert.ok(cypher.includes('CREATE (A {'));
    assert.ok(!cypher.includes('{}'));
  });

  it('deduplicates nodes by id', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: ['One'], properties: {} }, { id: 'A', labels: ['Two'], properties: {} }],
      [],
      {},
      false,
    );
    const matches = cypher.match(/CREATE \(A/g);
    assert.equal(matches?.length, 1);
  });

  it('deduplicates edge ids when collisions occur', () => {
    const cypher = toCypher(
      [{ id: 'A', labels: [], properties: {} }, { id: 'B', labels: [], properties: {} }],
      [
        { id: 'e1', source_id: 'A', target_id: 'B', type: 'x', properties: {} },
        { id: 'e1', source_id: 'A', target_id: 'B', type: 'y', properties: {} },
      ],
      {},
      false,
    );
    assert.ok(cypher.includes('[e1:`X`'));
    assert.ok(cypher.includes('[e1_1:`Y`'));
  });
});
